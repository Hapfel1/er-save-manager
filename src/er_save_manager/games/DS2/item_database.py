def _hex_id_to_int(hex_str: str) -> int | None:
    try:
        return int.from_bytes(bytes.fromhex(hex_str), "little")
    except ValueError:
        return None


def build_item_db() -> dict[int, tuple[str, str]]:
    """Build a single {item_id_int: (item_name, category)} lookup table."""
    item_db: dict[int, tuple[str, str]] = {}
    for category, names in CATEGORIES.items():
        for name, hex_id in names.items():
            item_id = _hex_id_to_int(hex_id)
            if item_id is not None:
                item_db[item_id] = (name, category)
    return item_db
