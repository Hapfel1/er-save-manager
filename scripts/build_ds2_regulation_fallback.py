"""
Build src/er_save_manager/games/DS2/regulation_vanilla.py.

Some DS2 saves hold an archive of SpEffect EMEVD files in the regulation
entry instead of the params. Regulation.from_container then falls back to the
tables in that module, which this script derives from the regulation of a
save that does carry the params. Use a save written by the unmodded game.

Usage:
    python scripts/build_ds2_regulation_fallback.py <DS2SOFS0000.sl2> [--out PATH]
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from er_save_manager.games.DS2.regulation import (  # noqa: E402
    REGULATION_ENTRY,
    Regulation,
)
from er_save_manager.games.DS2.save import DS2Container  # noqa: E402

DEFAULT_OUT = ROOT / "src/er_save_manager/games/DS2/regulation_vanilla.py"

HEADER = '''"""
Vanilla DS2 SotFS regulation tables, the fallback for saves whose regulation
entry holds no params. Generated by scripts/build_ds2_regulation_fallback.py;
do not edit by hand.

ITEMS: ItemParam row id -> (max held, max upgrade, durability or None,
infusion mask, attunement slots).
ATTUNEMENT_SLOTS: attunement level -> slot count.
CLASS_BASES: PlayerStatusParam row id -> (level, attributes by name).
LEVEL_UP_SOULS: level N -> soul cost of going to N + 1.
BOSS_FIGHTS: BossBattleParam (row id, killedEventId, onceKilledEventId,
bonfireEventValueId, bonfireId).
"""

from __future__ import annotations

'''


def build(save_path: Path) -> str:
    container = DS2Container.from_file(save_path)
    reg = Regulation.from_entry(container.get_entry(REGULATION_ENTRY))

    lines = [HEADER, "ITEMS: dict[int, tuple[int, int, float | None, int, int]] = {"]
    for item_id, info in sorted(reg._items.items()):
        lines.append(
            f"    {item_id}: ({info.max_held}, {info.max_upgrade}, "
            f"{info.durability!r}, {info.infusion_mask}, {info.spell_slots}),"
        )
    lines.append("}")

    lines.append("ATTUNEMENT_SLOTS: dict[int, int] = {")
    lines += [f"    {k}: {v}," for k, v in sorted(reg._attunement_slots.items())]
    lines.append("}")

    lines.append("CLASS_BASES: dict[int, tuple[int, dict[str, int]]] = {")
    for row_id, base in sorted(reg._class_bases.items()):
        lines.append(f"    {row_id}: ({base.level}, {base.stats!r}),")
    lines.append("}")

    lines.append("LEVEL_UP_SOULS: dict[int, int] = {")
    lines += [f"    {k}: {v}," for k, v in sorted(reg._level_up_souls.items())]
    lines.append("}")

    lines.append("BOSS_FIGHTS: tuple[tuple[int, int, int, int, int], ...] = (")
    for f in reg.boss_fights():
        lines.append(
            f"    ({f.row_id}, {f.killed_flag}, {f.once_killed_flag}, "
            f"{f.defeat_value}, {f.bonfire_id}),"
        )
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("save", type=Path)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    args.out.write_text(build(args.save), encoding="utf-8")
    # Match the repository style so a regenerate yields the committed file.
    for command in (["check", "--fix", "--quiet"], ["format", "--quiet"]):
        subprocess.run(["ruff", *command, str(args.out)], check=True)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
