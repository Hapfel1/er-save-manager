"""
Build src/er_save_manager/games/DS2/boss_arenas.py.

A boss fight's enemies are the generators of its map whose GeneratorParam
eventGroupId is one of the fight's BossBattleParam genEventGroupId1-3. The
fight's map is the map of its killedEventId. This covers the boss itself and
every enemy that spawns with it.

BossBattleParam is read from the regulation of a save that carries the params.
GeneratorParam files come from the unmodded game archive (GameDataEbl,
/param/generatorparam_m*_00_00.param); mods that edit them change the result.

Usage:
    python scripts/build_ds2_boss_arenas.py <DS2SOFS0000.sl2> <param dir> [--out PATH]
"""

from __future__ import annotations

import argparse
import struct
import subprocess
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from er_save_manager.games.DS2.regulation import (  # noqa: E402
    REGULATION_ENTRY,
    _Param,
    _read_bnd4,
)
from er_save_manager.games.DS2.save import DS2Container  # noqa: E402

DEFAULT_OUT = ROOT / "src/er_save_manager/games/DS2/boss_arenas.py"

# BossBattleParam
_BOSS_KILLED_FLAG = 0x10  # u32
_BOSS_GEN_EVENT_GROUPS = 0x28  # 3 x u8
# GeneratorParam
_GEN_EVENT_GROUP = 0x02  # u8

HEADER = '''"""
Enemies of DS2 boss fights. Generated by scripts/build_ds2_boss_arenas.py
from the game's BossBattleParam and GeneratorParam files; do not edit by hand.

ARENA_GENERATORS: BossBattleParam row id -> generator ids of the fight's boss
and enemies (GeneratorParam eventGroupId in the fight's genEventGroupId1-3).
The generators belong to the map of the fight's killedEventId.
"""

from __future__ import annotations

'''


def _boss_battles(save_path: Path) -> _Param:
    entry = DS2Container.from_file(save_path).get_entry(REGULATION_ENTRY)
    compressed_size = struct.unpack_from("<I", entry, 0)[0]
    payload = zlib.decompress(bytes(entry[8 : 8 + compressed_size]))
    start, size = _read_bnd4(payload)["BossBattleParam.param"]
    return _Param(payload, start, size, "BossBattleParam.param")


def _generators(path: Path) -> list[tuple[int, int]]:
    """(generator id, eventGroupId) of every row of a 64-bit DS2
    GeneratorParam file."""
    data = path.read_bytes()
    count = struct.unpack_from("<H", data, 0x0A)[0]
    rows = []
    for i in range(count):
        row_id, offset, _ = struct.unpack_from("<QQQ", data, 0x40 + 24 * i)
        rows.append((row_id, data[offset + _GEN_EVENT_GROUP]))
    return rows


def build(save_path: Path, param_dir: Path) -> dict[int, list[int]]:
    battles = _boss_battles(save_path)
    result: dict[int, list[int]] = {}
    for row_id in battles.ids():
        killed = battles.s32(row_id, _BOSS_KILLED_FLAG)
        groups = {battles.u8(row_id, _BOSS_GEN_EVENT_GROUPS + i) for i in range(3)} - {
            0
        }
        if killed <= 0 or not groups:
            continue
        area = killed // 100_000_000 * 10
        block = killed // 1_000_000 % 100
        path = param_dir / f"generatorparam_m{area:02d}_{block:02d}_00_00.param"
        if not path.exists():
            sys.exit(f"Missing {path.name} for BossBattleParam row {row_id}")
        generators = [g for g, group in _generators(path) if group in groups]
        if generators:
            result[row_id] = generators
    return result


def render(arenas: dict[int, list[int]]) -> str:
    lines = [HEADER, "ARENA_GENERATORS: dict[int, tuple[int, ...]] = {"]
    for row_id, generators in sorted(arenas.items()):
        lines.append(f"    {row_id}: ({', '.join(map(str, generators))},),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("save", type=Path)
    parser.add_argument("param_dir", type=Path)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    args.out.write_text(render(build(args.save, args.param_dir)), encoding="utf-8")
    subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--fix", "-q", str(args.out)],
        check=False,
    )
    subprocess.run([sys.executable, "-m", "ruff", "format", str(args.out)], check=False)
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
