"""
Build src/er_save_manager/games/DS2/npc_generators.py.

A map's record in a save holds one kill count per GeneratorParam row of that
map, in row order. This script reads the row order of every map's
GeneratorParam and keeps the rows of the generators listed in npc_database.

Use the unmodded game's param files (Game/Param/generatorparam_m*_00_00.param);
mods that add or remove generator rows change the order.

Usage:
    python scripts/build_ds2_npc_generators.py <param dir> [--out PATH]
"""

from __future__ import annotations

import argparse
import re
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from er_save_manager.games.DS2.npc_database import NPCS  # noqa: E402

DEFAULT_OUT = ROOT / "src/er_save_manager/games/DS2/npc_generators.py"
FILE_PATTERN = re.compile(r"generatorparam_m(\d\d)_(\d\d)_00_00\.param$")

HEADER = '''"""
Kill count positions of the NPC generators in npc_database. Generated by
scripts/build_ds2_npc_generators.py from the game's GeneratorParam files;
do not edit by hand.

GENERATOR_ROWS: generator id -> ((map id, row index in that map's
GeneratorParam), ...). Map ids are area << 24 | block << 16, as in the save's
map records.
"""

from __future__ import annotations

'''


def row_ids(path: Path) -> list[int]:
    """Row ids of a 64-bit DS2 param file, in file order."""
    data = path.read_bytes()
    count = struct.unpack_from("<H", data, 0x0A)[0]
    return [struct.unpack_from("<Q", data, 0x40 + 24 * i)[0] for i in range(count)]


def build(param_dir: Path) -> dict[int, list[tuple[int, int]]]:
    wanted = {g for npc in NPCS for g in npc.generators}
    rows: dict[int, list[tuple[int, int]]] = {g: [] for g in sorted(wanted)}
    for path in sorted(param_dir.iterdir()):
        match = FILE_PATTERN.match(path.name)
        if match is None:
            continue
        map_id = int(match.group(1)) << 24 | int(match.group(2)) << 16
        for index, generator in enumerate(row_ids(path)):
            if generator in wanted:
                rows[generator].append((map_id, index))
    return rows


def render(rows: dict[int, list[tuple[int, int]]]) -> str:
    lines = [HEADER, "GENERATOR_ROWS: dict[int, tuple[tuple[int, int], ...]] = {"]
    for generator, places in rows.items():
        inner = ", ".join(f"(0x{m:08X}, {i})" for m, i in sorted(places))
        lines.append(f"    {generator}: ({inner},),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("param_dir", type=Path)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    rows = build(args.param_dir)
    missing = [g for g, places in rows.items() if not places]
    if missing:
        sys.exit(f"Generators not found in any map: {missing}")
    args.out.write_text(render(rows), encoding="utf-8")
    subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--fix", "-q", str(args.out)],
        check=False,
    )
    subprocess.run([sys.executable, "-m", "ruff", "format", str(args.out)], check=False)
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
